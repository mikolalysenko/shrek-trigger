// Samples the generated jar into one native 32x32 frame with a private
// twelve-color palette: mask the magenta key, crop to the prop, area-average
// down to fit 28x30 (bottom-centered, like a standing NPC), then reduce the
// colors with a fixed-seed k-means. Entry 1 is the darkest color, as native
// palettes expect. Integer transforms of generated pixels only; nothing is
// drawn. Run `node assets/imagegen/onion-jar/sample.mjs` to rewrite
// content/onion-jar-art.js after replacing the source.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {PNG} from 'pngjs';
const source=new URL('./source-v2.png',import.meta.url);
export async function sampleOnionJar({width=28,height=30}={}){
 const bytes=await readFile(source),im=PNG.sync.read(bytes);
 const key=(r,g,b)=>r>170&&b>170&&g<110;
 let x0=im.width,y0=im.height,x1=0,y1=0;
 for(let y=0;y<im.height;y++)for(let x=0;x<im.width;x++){const p=(y*im.width+x)*4;if(!key(im.data[p],im.data[p+1],im.data[p+2])){x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}}
 const scale=Math.max((x1-x0+1)/width,(y1-y0+1)/height),w=Math.round((x1-x0+1)/scale),h=Math.round((y1-y0+1)/scale),ox=(32-w)>>1,oy=32-h;
 const samples=[];
 for(let y=0;y<h;y++)for(let x=0;x<w;x++){
  let r=0,g=0,b=0,n=0,total=0;
  for(let sy=Math.floor(y0+y*scale);sy<Math.floor(y0+(y+1)*scale);sy++)for(let sx=Math.floor(x0+x*scale);sx<Math.floor(x0+(x+1)*scale);sx++){
   const p=(sy*im.width+sx)*4;total++;if(key(im.data[p],im.data[p+1],im.data[p+2]))continue;r+=im.data[p];g+=im.data[p+1];b+=im.data[p+2];n++;
  }
  if(n*2>=total)samples.push({i:(oy+y)*32+ox+x,c:[r/n,g/n,b/n]});
 }
 // k-means, seeded from evenly spaced samples sorted by brightness.
 const sorted=[...samples].sort((a,z)=>a.c[0]+a.c[1]+a.c[2]-z.c[0]-z.c[1]-z.c[2]);
 let centers=Array.from({length:12},(_,k)=>sorted[Math.floor((k+0.5)*sorted.length/12)].c.slice());
 const nearest=c=>{let best=0,bd=Infinity;centers.forEach((m,i)=>{const d=(m[0]-c[0])**2+(m[1]-c[1])**2+(m[2]-c[2])**2;if(d<bd){bd=d;best=i;}});return best;};
 for(let pass=0;pass<24;pass++){
  const sums=centers.map(()=>[0,0,0,0]);
  for(const s of samples){const k=nearest(s.c);sums[k][0]+=s.c[0];sums[k][1]+=s.c[1];sums[k][2]+=s.c[2];sums[k][3]++;}
  centers=centers.map((m,i)=>sums[i][3]?[sums[i][0]/sums[i][3],sums[i][1]/sums[i][3],sums[i][2]/sums[i][3]]:m);
 }
 // SNES colors have five bits per channel.
 centers=centers.map(m=>m.map(v=>{const q=Math.round(v/255*31);return q<<3|q>>2;}));
 const order=centers.map((m,i)=>i).sort((a,z)=>centers[a][0]+centers[a][1]+centers[a][2]-centers[z][0]-centers[z][1]-centers[z][2]),rank=new Map(order.map((k,i)=>[k,i]));
 const pixels=new Uint8Array(1024);for(const s of samples)pixels[s.i]=rank.get(nearest(s.c))+1;
 const palette=order.map(k=>centers[k].map(v=>v.toString(16).padStart(2,'0')).join(''));
 return{pixels,palette,sourceSha256:createHash('sha256').update(bytes).digest('hex')};
}
if(process.argv[1]&&import.meta.url.endsWith(process.argv[1].replace(/^.*assets/,'assets'))){
 const {pixels,palette,sourceSha256}=await sampleOnionJar();
 const rows=Array.from({length:32},(_,y)=>"  '"+[...pixels.subarray(y*32,y*32+32)].map(v=>v.toString(16)).join('')+"'");
 await writeFile(new URL('../../../content/onion-jar-art.js',import.meta.url),`// Generated by assets/imagegen/onion-jar/sample.mjs from source-v2.png
// (OpenAI Images API; prompt and request ID beside it). One hex digit per
// pixel: 0 is transparent, 1-c index the palette below.
export const onionJarArt={
 source:'assets/imagegen/onion-jar/source-v2.png',
 sourceSha256:'${sourceSha256}',
 palette:${JSON.stringify(palette)},
 rows:[
${rows.join(',\n')}
 ]
};
`);
 console.log('wrote content/onion-jar-art.js',palette.join(' '));
}
