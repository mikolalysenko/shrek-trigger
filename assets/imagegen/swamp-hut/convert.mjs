// Converts the selected gpt-image-2 swamp home (sources/hut.png) into the
// 32x32 present-day world-map landmark (content/swamp-hut-art.js), indexed in
// world palette row 3 (the map's foliage greens and bark browns).
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {u16,u24,fileOffset} from '../../../engine/rom.js';
import {decompress} from '../../../engine/compression.js';

const require=createRequire(import.meta.url);
const {PNG}=require('pngjs');
export const hutPaletteRow=3;
// The native footprint leaves the top-right 8x8 and bottom-left 16x8 cells empty.
export const hutAllowed=(x,y)=>!((x>=24&&y<8)||(x<16&&y>=24));
const lin=c=>{c/=255;return c<=.04045?c/12.92:((c+.055)/1.055)**2.4;};
function lab(r,g,b){
  const R=lin(r),G=lin(g),B=lin(b),f=t=>t>.008856?Math.cbrt(t):7.787*t+16/116;
  const X=f((R*.4124+G*.3576+B*.1805)/.95047),Y=f(R*.2126+G*.7152+B*.0722),Z=f((R*.0193+G*.1192+B*.9505)/1.08883);
  return [116*Y-16,500*(X-Y),200*(Y-Z)];
}

export function convertSwampHut(base){
  const wp=decompress(base,fileOffset(u24(base,0x6fea0+4*3))).bytes;
  const row=Array.from({length:16},(_,i)=>{const v=u16(wp,(hutPaletteRow*16+i)*2);return [(v&31)*255/31,(v>>5&31)*255/31,(v>>10&31)*255/31];});
  const p=PNG.sync.read(readFileSync(new URL('./sources/hut.png',import.meta.url))),{width:w,height:h,data:d}=p;
  // Flat magenta key, then area-average 32x32 source blocks.
  const out=new Uint8Array(1024),palLab=row.map(c=>lab(...c));
  let outline=1,dark=1e9;for(let j=1;j<16;j++)if(palLab[j][0]<dark){dark=palLab[j][0];outline=j;}
  for(let ty=0;ty<32;ty++)for(let tx=0;tx<32;tx++){
    if(!hutAllowed(tx,ty))continue;
    let A=0,R=0,G=0,B=0,n=0;
    for(let y=ty*h/32|0;y<(ty+1)*h/32;y++)for(let x=tx*w/32|0;x<(tx+1)*w/32;x++){const i=(y*w+x)*4,k=Math.min(d[i],d[i+2])-d[i+1],a=k<=60?1:k>=140?0:1-(k-60)/80;A+=a;R+=d[i]*a;G+=d[i+1]*a;B+=d[i+2]*a;n++;}
    if(A/n<.5)continue;
    const L=lab(R/A,G/A,B/A);let bi=1,bd=1e18;
    for(let j=1;j<16;j++){const q=palLab[j],dd=(q[0]-L[0])**2+(q[1]-L[1])**2+(q[2]-L[2])**2;if(dd<bd){bd=dd;bi=j;}}
    out[ty*32+tx]=bi;
  }
  const o=out.slice();
  for(let y=0;y<32;y++)for(let x=0;x<32;x++){const i=y*32+x;if(!out[i])continue;const t=(xx,yy)=>xx<0||yy<0||xx>=32||yy>=32||!out[yy*32+xx];if(t(x-1,y)||t(x+1,y)||t(x,y-1)||t(x,y+1))o[i]=outline;}
  // Hand-finished door and window, too small to survive the resample:
  // d near-black outline, f dark bark, e bark, 1 warm light (row 3 indices).
  const D=[[13,14,'dddd'],[14,13,'dffffd'],[15,12,'dfefefed'],[16,12,'dfefefed'],[17,12,'dfefefed'],[18,12,'dfefe1ed'],[19,12,'dfefefed'],[20,12,'dfefefed'],[21,12,'dfefefed'],[22,12,'dfefefed'],[23,12,'dddddddd'],
    [13,21,'dddd'],[14,21,'d11d'],[15,21,'d11d'],[16,21,'dddd']];
  for(const [y,x0,str] of D)for(let i=0;i<str.length;i++)o[y*32+x0+i]=parseInt(str[i],16);
  const rows=Array.from({length:32},(_,y)=>Array.from(o.slice(y*32,y*32+32),v=>v.toString(16)).join(''));
  return `// Generated by scripts/import-swamp-hut-art.mjs from assets/imagegen/swamp-hut
// (see its README); do not edit by hand. Indexed rows of hex digits in world
// palette row ${hutPaletteRow}: 0 transparent, 1-f that row's native colors.
export const swampHutArt = ${JSON.stringify({paletteRow:hutPaletteRow,width:32,height:32,rows},null,1)};
`;
}
