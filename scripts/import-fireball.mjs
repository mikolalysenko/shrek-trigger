import{readFile,writeFile,mkdir}from'node:fs/promises';
import{createHash}from'node:crypto';
import{readMidi}from'../engine/midi.js';

// Quotes the phrases the Mr. Worldwide battle theme uses from the "Fireball"
// MIDI supplied by the user. The file itself stays private under
// .local/music/; only these quoted phrases are stored in the repository.
//
//   node scripts/import-fireball.mjs [/path/to/fireball.mid]
//
// Onsets are the file's own, at 48 ticks per quarter note (the file uses
// 384). The tenor-sax chop is quantised to sixteenths because the file plays
// it slightly ahead of the beat; every other part is already on the grid.
// Durations are articulations for the SNES voices: the file's note length
// rounded to the driver's three-tick grid, at least six ticks and never past
// the next onset in the same part.
export async function importFireball(path='.local/music/fireball-source.mid'){
  const bytes=await readFile(path),midi=readMidi(bytes),sha256=createHash('sha256').update(bytes).digest('hex');
  const track=midi.tracks[0],bpm=Math.round(60e6/midi.tempos[0].microseconds);
  if(midi.format!==0||midi.tracks.length!==1||midi.ppq!==384||bpm!==123||midi.ticks!==38400)throw Error('This arranger expects the supplied single-track 123 BPM Fireball MIDI');
  const scale=midi.ppq/48,bar=192;
  const notes=(channel,from,to,{grid=0,select}={})=>{
    const groups=new Map();
    for(const n of track.notes){
      if(n.channel!==channel)continue;
      let at=n.at/scale;if(grid)at=Math.round(at/grid)*grid;
      if(!Number.isInteger(at))throw Error('Fireball channel '+channel+' leaves the 48-tick grid');
      if(at<from*bar||at>=to*bar)continue;
      if(!groups.has(at))groups.set(at,[]);groups.get(at).push(n);
    }
    const onsets=[...groups.keys()].sort((a,b)=>a-b);
    return onsets.flatMap((at,i)=>{
      const chord=groups.get(at).sort((a,b)=>a.pitch-b.pitch),next=onsets[i+1]??to*bar;
      const picked=select?select(chord):[chord.at(-1)];
      return picked.map(n=>{
        const ticks=Math.min(next-at,Math.max(6,Math.round(n.duration/scale/3)*3));
        return[Math.floor(at/bar)-from,at%bar,ticks,n.pitch];
      });
    });
  };
  // Drum hits by General MIDI key: [bar, tick, key].
  const drums=(from,to)=>track.notes.filter(n=>n.channel===9&&n.at/scale>=from*bar&&n.at/scale<to*bar)
    .map(n=>[Math.floor(n.at/scale/bar)-from,n.at/scale%bar,n.pitch]).sort((a,b)=>a[0]-b[0]||a[1]-b[1]||a[2]-b[2]);
  const phrases={
    // The horn hook (trumpet, channel 8; doubled by channels 5 and 7).
    hook:{channel:8,from:18,bars:2,notes:notes(8,18,20)},
    // The bass riff under the hook (channel 1).
    bass:{channel:1,from:18,bars:2,notes:notes(1,18,20)},
    // The strummed vamp (channel 6): top and inner voice of each strum.
    strumTop:{channel:6,from:2,bars:2,notes:notes(6,2,4)},
    strumInner:{channel:6,from:2,bars:2,notes:notes(6,2,4,{select:c=>[c.at(-2)??c.at(-1)]})},
    // The low tenor-sax chop that drives the verse (channel 3), used in the build.
    chop:{channel:3,from:6,bars:4,grid:12,notes:notes(3,6,10,{grid:12})},
    // Percussion: the drop's groove and the fill into the stop and the drop.
    hookDrums:{channel:9,from:18,bars:2,notes:drums(18,20)},
    fillDrums:{channel:9,from:16,bars:2,notes:drums(16,18)}
  };
  return{sha256,bpm,ppq:midi.ppq,bars:midi.ticks/midi.ppq/4,phrases};
}

if(import.meta.url===`file://${process.argv[1]}`){
  const source=process.argv[2]??'.local/music/fireball-source.mid';
  const{sha256,bpm,ppq,bars,phrases}=await importFireball(source);
  await mkdir('.local/music',{recursive:true});
  if(source!=='.local/music/fireball-source.mid')await writeFile('.local/music/fireball-source.mid',await readFile(source));
  const body=Object.entries(phrases).map(([key,p])=>`export const ${key}=${JSON.stringify(p)};`).join('\n');
  await writeFile('content/music-fireball-phrases.js',
`// Generated by scripts/import-fireball.mjs from the "Fireball" (Pitbull) MIDI
// supplied by the user. The MIDI stays private under .local/music/. Only the
// phrases below are quoted. Each note is [bar, tick, ticks, pitch] in the
// file's own key (F): bar 0 is source bar \`from\`, ticks are 48 per quarter.
// Drum entries are [bar, tick, General MIDI key].
export const fireballSource=${JSON.stringify({file:'fireball.mid',sha256,providedBy:'user',composition:'Fireball — Pitbull',bpm,ppq,bars})};
${body}
// Places a phrase's notes from \`start\` ticks, transposed by \`transpose\`
// semitones, optionally mapping each pitch afterwards.
export function place(phrase,start,transpose=0,map=p=>p){
  return phrase.notes.map(([bar,tick,ticks,pitch])=>[start+bar*192+tick,ticks,map(pitch+transpose)]);
}
`);
  console.log(JSON.stringify({sha256,bpm,bars,phrases:Object.fromEntries(Object.entries(phrases).map(([k,p])=>[k,p.notes.length]))}));
}
