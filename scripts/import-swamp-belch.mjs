import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),dir='assets/imagegen/swamp-belch/';
const source=await readFile(new URL(dir+'source-v1.png',root)),indexed=JSON.parse(await readFile(new URL(dir+'native-64/indexed.json',root)));
const hash=createHash('sha256').update(source).digest('hex');
if(hash!==indexed.sourceSha256||indexed.width!==64||indexed.height!==64||indexed.frames.length!==8)throw Error('Swamp Belch source packet changed');
const asset={width:64,height:64,palette:indexed.palette,pixels:indexed.frames[7],source:dir+'source-v1.png',sourceSha256:hash,sourcePhase:7,sourceType:'imagegen',sampling:indexed.sampling};
await writeFile(new URL('engine/swamp-belch-raster.js',root),'// Generated by scripts/import-swamp-belch.mjs from the saved imagegen source.\nexport const swampBelchRaster='+JSON.stringify(asset)+';\n');
console.log('Imported Swamp Belch generated cloud, source phase 7 at 64 × 64.');
