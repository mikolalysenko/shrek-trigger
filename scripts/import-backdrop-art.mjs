// Samples a generated picture into the three-color raster a battle backdrop
// effect draws on BG3 (the format engine/swamp-belch-art.js reads): mask the
// flat green key, area-average to SIZE x SIZE, and reduce the remaining
// pixels to three colors with a fixed-seed k-means, darkest first.
//   node scripts/import-backdrop-art.mjs assets/imagegen/call-my-wife/source-v1.png engine/call-my-wife-raster.js callMyWifeRaster [size]
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {PNG} from 'pngjs';
const [src,out,name,sizeArg]=process.argv.slice(2),N=+(sizeArg??64);
const bytes=await readFile(src),im=PNG.sync.read(bytes),key=(r,g,b)=>g>200&&r<90&&b<90;
const cells=[];
for(let y=0;y<N;y++)for(let x=0;x<N;x++){
 let r=0,g=0,b=0,n=0,total=0;
 for(let sy=Math.floor(y*im.height/N);sy<Math.floor((y+1)*im.height/N);sy++)for(let sx=Math.floor(x*im.width/N);sx<Math.floor((x+1)*im.width/N);sx++){
  const p=(sy*im.width+sx)*4;total++;if(key(im.data[p],im.data[p+1],im.data[p+2]))continue;r+=im.data[p];g+=im.data[p+1];b+=im.data[p+2];n++;
 }
 cells.push(n*2>=total?[r/n,g/n,b/n]:null);
}
const solid=cells.filter(Boolean),lum=c=>c[0]*.3+c[1]*.59+c[2]*.11,sorted=[...solid].sort((a,z)=>lum(a)-lum(z));
let centers=[.17,.5,.83].map(q=>sorted[Math.floor(q*sorted.length)].slice());
const nearest=c=>{let best=0,bd=Infinity;centers.forEach((m,i)=>{const d=(m[0]-c[0])**2+(m[1]-c[1])**2+(m[2]-c[2])**2;if(d<bd){bd=d;best=i;}});return best;};
for(let pass=0;pass<24;pass++){const sums=centers.map(()=>[0,0,0,0]);for(const c of solid){const k=nearest(c);sums[k][0]+=c[0];sums[k][1]+=c[1];sums[k][2]+=c[2];sums[k][3]++;}centers=centers.map((m,i)=>sums[i][3]?sums[i].slice(0,3).map(v=>v/sums[i][3]):m);}
const order=[0,1,2].sort((a,z)=>lum(centers[a])-lum(centers[z])),rank=new Map(order.map((k,i)=>[k,i+1]));
const palette=order.map(k=>centers[k].map(v=>{const q=Math.round(v/255*31);return(q<<3|q>>2).toString(16).padStart(2,'0');}).join(''));
const pixels=cells.map(c=>c?rank.get(nearest(c)):0).join('');
const asset={width:N,height:N,palette,pixels,source:src,sourceSha256:createHash('sha256').update(bytes).digest('hex'),sourceType:'imagegen',sampling:'green key, area average, 3-color k-means'};
await writeFile(out,`// Generated by scripts/import-backdrop-art.mjs from the saved imagegen source.\nexport const ${name}=${JSON.stringify(asset)};\n`);
console.log('wrote',out,palette.join(' '));
