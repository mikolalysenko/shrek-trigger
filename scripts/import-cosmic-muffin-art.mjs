import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {sampleBody,palette} from '../assets/imagegen/cosmic-muffin-shell/sample-body.mjs';
import {sampleWorld} from '../assets/imagegen/cosmic-muffin-world/sample-world.mjs';
import {sampleMeteor} from '../assets/imagegen/cosmic-muffin-world/sample-meteor.mjs';
import {compileBody as compileInteriorBody} from '../assets/imagegen/cosmic-muffin-interior/compile-body.mjs';

// Source sampling only: no anatomical pixel drawing or runtime image decoder.
const root=new URL('../',import.meta.url),base=await readFile(new URL('.local/chrono-trigger-usa.sfc',root));
const sha=b=>createHash('sha256').update(b).digest('hex');
assert.equal(sha(base),'06d1c2b06b716052c5596aaa0c2e5632a027fee1a9a28439e509f813c30829a9');
const body=sampleBody(126,'area'),world=sampleWorld(base,{targetWidth:64,method:'area'}),meteor=sampleMeteor(base,{targetWidth:48,bottom:49,method:'area'});
const data={body:{...body,palette},world,meteor};
for(const [key,r]of Object.entries(data)){
 assert.deepEqual(r.audit.outsideNativeCoverage,[],key+' source fits native coverage');
 assert.equal(sha(r.pixels),r.audit.pixelsSha256,key+' source pixels');
 data[key]={pixels:Array.from(r.pixels,v=>v.toString(16)).join(''),palette:r.palette,audit:r.audit};
}
const interior=compileInteriorBody(),hex=b=>Buffer.from(b).toString('hex');
const interiorData={backgrounds:interior.banks.map(b=>({id:b.id,bytes:hex(b.graphics)})),pulse:hex(interior.pulse.graphics),metatiles:hex(interior.assembly),palette:interior.body.palette.slice(1),audit:interior.report,pulseAudit:interior.pulse.report};
await writeFile(new URL('engine/generated-cosmic-muffin-art.js',root),'// Generated by scripts/import-cosmic-muffin-art.mjs from the accepted PNG sources.\nexport const cosmicMuffinRaster='+JSON.stringify(data)+';\nexport const cosmicMuffinInteriorRaster='+JSON.stringify(interiorData)+';\n');
console.log('Imported Cosmic Muffin exterior, world, meteor and living oven interior source pixels.');
