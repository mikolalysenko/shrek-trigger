import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {PNG} from 'pngjs';

// Tyson-only native conversion. Area sampling erases the one-pixel black ink
// in the supplied sheet, so retain meaningful ink and eye-highlight coverage
// before falling back to the ordinary area-majority color.
const root=resolve(import.meta.dirname,'..');
const directory=resolve(root,'assets/raster/tyson');
const spec=JSON.parse(await readFile(resolve(directory,'import-spec.json'),'utf8'));
if(spec.key!=='tyson'||spec.width!==48||spec.height!==64||spec.palette.length!==12)throw Error('Unexpected Tyson native contract');
const sheet=spec.sheets[0],linework=sheet.linework;
if(!linework)throw Error('Tyson import spec needs its separate linework settings');
const bytes=await readFile(resolve(root,sheet.file)),image=PNG.sync.read(bytes);
const chroma=new Set((sheet.chromaKey??[]).map(c=>parseInt(c,16)));
const rgb=hex=>[0,1,2].map(i=>parseInt(hex.slice(i*2,i*2+2),16));
const colors=spec.samplingPalette.map(rgb),sourceColor=new Map(colors.map((c,i)=>[(c[0]<<16)|(c[1]<<8)|c[2],i+1]));
const ink=sourceColor.get(0),highlight=sourceColor.get(0xffffff);
if(ink!==1||!highlight)throw Error('Tyson sampling palette needs black ink and white highlights');
const widths=spec.width,heights=spec.height,inkRatio=linework.inkRatio??.2,highlightRatio=linework.highlightRatio??.18,coverage=linework.coverageThreshold??.28;
const regions=sheet.regions;
const heightsForScale=(sheet.scaleCells??[0,1,2,3]).map(i=>regions[i][3]).sort((a,b)=>a-b);
const scale=(sheet.nativeHeight??57)/heightsForScale[Math.floor(heightsForScale.length/2)];

function convert([x0,y0,w,h]){
  const sw=Math.max(1,Math.round(w*scale*(sheet.sample.scaleX??1))),sh=Math.max(1,Math.round(h*scale));
  if(sw>widths||sh>heights)throw Error(`Tyson source ${w}x${h} exceeds native cell at ${sw}x${sh}`);
  const ox=Math.floor((widths-sw)/2),oy=heights-2-sh+1,pixels=new Uint8Array(widths*heights);
  for(let y=0;y<sh;y++)for(let x=0;x<sw;x++){
    const ax=x0+x*w/sw,bx=x0+(x+1)*w/sw,ay=y0+y*h/sh,by=y0+(y+1)*h/sh;
    const votes=new Float64Array(13);let opacity=0,black=0,white=0;
    for(let yy=Math.floor(ay);yy<Math.ceil(by);yy++)for(let xx=Math.floor(ax);xx<Math.ceil(bx);xx++){
      const p=(yy*image.width+xx)*4,key=(image.data[p]<<16)|(image.data[p+1]<<8)|image.data[p+2];
      if(chroma.has(key)||image.data[p+3]<96)continue;
      const color=sourceColor.get(key);if(!color)throw Error(`Unmapped Tyson source color ${key.toString(16).padStart(6,'0')} at ${xx},${yy}`);
      const weight=(Math.min(bx,xx+1)-Math.max(ax,xx))*(Math.min(by,yy+1)-Math.max(ay,yy))*image.data[p+3]/255;
      opacity+=weight;votes[color]+=weight;if(color===ink)black+=weight;if(color===highlight)white+=weight;
    }
    const area=(bx-ax)*(by-ay);if(!opacity||opacity/area<coverage)continue;
    let color=0;
    // White source pixels are eyes, teeth and glove highlights. Keep them only
    // when they have real coverage; isolated chroma or subpixel noise cannot
    // create a native highlight. Ink otherwise wins over averaged body color.
    if(white/opacity>=highlightRatio)color=highlight;
    else if(black/opacity>=inkRatio)color=ink;
    else{
      votes[ink]=0;votes[highlight]=0;
      for(let i=1;i<votes.length;i++)if(votes[i]>votes[color])color=i;
    }
    pixels[(oy+y)*widths+ox+x]=color;
  }
  if(!pixels.some(Boolean))throw Error('Converted Tyson frame is blank');
  return pixels;
}

const frames=regions.map(convert),native=spec.sequences.native?.[1];
if(frames.length!==36||native?.length!==45)throw Error('Tyson requires 36 source frames and 45 native slots');
for(const sequence of Object.values(spec.sequences))for(const list of Object.values(sequence))for(const entry of list){
  const index=typeof entry==='number'?entry:entry.frame;
  if(!Number.isInteger(index)||!frames[index])throw Error('Tyson sequence references a missing source frame');
}
const encoded=frames.map(p=>Array.from(p,v=>v.toString(16)).join(''));
const provenance=[{file:sheet.file,sha256:createHash('sha256').update(bytes).digest('hex'),sourceType:spec.sourceType,dimensions:[image.width,image.height]}];
const output=`// Generated by scripts/import-tyson-linework.mjs from the supplied Tyson sheet.\n// Do not edit pixels here; tune the Tyson-specific importer and re-run it.\nexport const tysonLinework=${JSON.stringify({width:widths,height:heights,palette:spec.palette,sourceType:spec.sourceType,frames:encoded,sequences:spec.sequences,provenance})};\n\nexport function tysonLineworkSprite(pose='guard',phase=0){\n  const sequence=tysonLinework.sequences[pose]?.[1];\n  if(!sequence)throw Error('Unassigned Tyson linework pose '+pose+'/'+phase);\n  const entry=sequence[phase%sequence.length],frame=typeof entry==='number'?entry:entry.frame;\n  const source=Uint8Array.from(tysonLinework.frames[frame],c=>parseInt(c,16)),pixels=new Uint8Array(tysonLinework.width*tysonLinework.height);\n  const mirror=typeof entry==='object'&&entry.flip;\n  for(let y=0;y<tysonLinework.height;y++)for(let x=0;x<tysonLinework.width;x++)pixels[y*tysonLinework.width+x]=source[y*tysonLinework.width+(mirror?tysonLinework.width-1-x:x)];\n  return pixels;\n}\n`;
await writeFile(resolve(root,'engine/tyson-linework.js'),output);
const atlas=new PNG({width:8*widths,height:Math.ceil(frames.length/8)*heights});
const outputColors=spec.palette.map(rgb);
frames.forEach((frame,i)=>frame.forEach((value,p)=>{if(!value)return;const [r,g,b]=outputColors[value-1],q=(((Math.floor(i/8)*heights+Math.floor(p/widths))*atlas.width)+(i%8)*widths+p%widths)*4;atlas.data.set([r,g,b,255],q);}));
await writeFile(resolve(directory,'native-indexed.png'),PNG.sync.write(atlas));
const report={key:'tyson',frames:frames.length,nativeFrames:native.length,width:widths,height:heights,opaqueColors:12,palette:spec.palette,samplingPalette:spec.samplingPalette,sources:[{...provenance[0],scale,chromaKey:sheet.chromaKey,regions,sample:{...sheet.sample,...linework,method:'linework'},frames:regions.map((bounds,cell)=>({cell,bounds}))}],sequences:spec.sequences};
await writeFile(resolve(directory,'import.json'),JSON.stringify(report,null,2)+'\n');
console.log(`Tyson linework: ${frames.length} source frames, ${native.length} native slots, ${widths}x${heights}`);
