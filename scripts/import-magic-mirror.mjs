// Copy the frozen indexed source rasters into a browser-readable module.
// The runtime compiler samples these pixels; this importer draws no artwork.
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {crc32} from '../engine/bps.js';

const root=new URL('../',import.meta.url),sha=b=>createHash('sha256').update(b).digest('hex');
const selected=[
  ['model','magic-mirror-model','dc0d5cf1e023a1b8b5848bee75648528bdbee7d83318191929d35c2f24974ffd'],
  ['display','magic-mirror-display','3cf1b7dee3b25f50c1ae605a00e2fa7fd335807a2d787164838a290a1ba50be4']
];
const assets={};
for(const [key,directory,expected]of selected){
  const file=`assets/raster/${directory}/draft/preview-raster.json`,bytes=await readFile(new URL(file,root));
  assert.equal(sha(bytes),expected,file+' approved indexed source');
  const source=JSON.parse(bytes);
  for(const p of source.provenance)assert.equal(sha(await readFile(new URL(p.file,root))),p.sha256,p.file);
  assets[key]={key:source.key,sourceType:source.sourceType,width:source.width,height:source.height,palette:source.palette,
    frames:source.frames,frameCrc32:source.frames.map(s=>crc32(Uint8Array.from(s,c=>parseInt(c,16)))),
    provenance:source.provenance,indexedSource:{file,sha256:expected}};
}
assets.archive={file:'assets/raster/magic-mirror-model/source-362695.zip',sha256:'b9eca77a6737e160ab060a87f2d710a35098c9913f5bd279a456b9a0cce53e34',
  page:'https://models.spriters-resource.com/xbox/shrek/asset/362695/page-1/',game:'Shrek (Xbox)',type:'existing-game-model-render'};
const text='// Generated by scripts/import-magic-mirror.mjs from the frozen source rasters.\nexport const magicMirrorRaster='+JSON.stringify(assets,null,2)+';\n';
const destination=new URL('assets/raster/magic-mirror-art.js',root);
if(process.argv.includes('--check'))assert.equal(await readFile(destination,'utf8'),text,'Magic Mirror browser source is reproducible');
else await writeFile(destination,text);
console.log(JSON.stringify({sourceFrames:8,opaqueColors:12,sourcePixels:48*96+7*32*16,output:'assets/raster/magic-mirror-art.js',sha256:sha(text),check:process.argv.includes('--check')}));
