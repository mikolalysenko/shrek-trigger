import {nativeRoutine} from './asm.js';
import {put24,u24} from './rom.js';

// Select an alternate assembly of the SAME PC graphics bank. Only equipped
// weapon IDs 61/66 change the silhouette. No additional VRAM, palette, cache
// entry or persistent WRAM is needed; every original frame and timer survives.
export function patchHatchetWeapon(base,frames,allocate,add){
  if(u24(base,0x24200c)!==0xd30000)throw Error('Puss graphics bank signature changed');
  const assembly=allocate(frames,'Puss equipped hatchet frame assembly'),lo=assembly&255,hi=assembly>>8&255,bank=0xc0|assembly>>16;
  const hooks=[];
  function install(offset,expected,bytes,kind,label){
    if(!expected.every((v,i)=>base[offset+i]===v))throw Error('Native hatchet boundary changed: '+label);
    const address=allocate(bytes,label+' routine'),call=new Uint8Array(expected.length).fill(0xea);call[0]=kind;put24(call,1,0xc00000|address);add(offset,call,label);
    hooks.push({offset,address,bytes:bytes.length,kind:kind===0x22?'JSL':'JML',label});
  }
  const field=nativeRoutine(a=>{
    a.emit(0xad,0x16,0x42,0x48); // Native frame * 40, saved on the stack.
    a.emit(0xbd,0x80,0x12);a.branch(0xd0,'original');
    a.emit(0xbd,0x00,0x12,0x29,0xff,0x00,0xc9,0xd3,0x00);a.branch(0xd0,'original');
    a.emit(0xaf,0x69,0x27,0x7e,0x29,0xff,0x00,0xc9,61,0);a.branch(0xf0,'hatchet');a.emit(0xc9,66,0);a.branch(0xd0,'original');
    a.label('hatchet');a.emit(0xe2,0x20,0xa9,bank,0x85,0xd5,0xc2,0x20,0x68,0x18,0x69,lo,hi,0x6b);
    a.label('original');a.emit(0x68,0x18,0x7d,0x80,0x13,0x6b);
  });
  install(0xcc34,[0xad,0x16,0x42,0x18,0x7d,0x80,0x13],field,0x22,'hatchet field frame selection');

  const battlePrefix=[0xc2,0x21,0xbd,0x78,0x1c,0x65,0xa9,0x85,0xba,0xbd,0x57,0x1c,0x85,0xbd,0x7b,0xe2,0x20,0x8b,0xbd,0x7a,0x1c,0x85,0xbc,0xbd,0x59,0x1c,0x48];
  const battle=nativeRoutine(a=>{
    // Preserve the native DB stack setup before returning with JML. A JSL
    // here would put its return address beneath the two pushed bank bytes.
    a.emit(...battlePrefix,0xc9,0xd3);a.branch(0xd0,'done');
    a.emit(0xa5,0xbd,0x05,0xbe);a.branch(0xd0,'done');
    a.emit(0xaf,0x69,0x27,0x7e,0xc9,61);a.branch(0xf0,'hatchet');a.emit(0xc9,66);a.branch(0xd0,'done');
    a.label('hatchet');a.emit(0xa9,bank,0x85,0xbc,0xc2,0x21,0xa9,lo,hi,0x65,0xa9,0x85,0xba,0x7b,0xe2,0x20);
    a.label('done');a.emit(0xbd,0x59,0x1c,0x5c,0xa4,0x1c,0xc1);
  });
  install(0x11c89,battlePrefix,battle,0x5c,'hatchet battle frame selection');

  const menuPrefix=[0xbf,0x01,0x00,0xe4,0x85,0x08,0xbf,0x00,0x00,0xe4,0x85,0x07];
  const menu=nativeRoutine(a=>{
    a.emit(...menuPrefix,0xe0,0x0c,0x23);a.branch(0xd0,'done');
    a.emit(0xaf,0x69,0x27,0x7e,0x29,0xff,0x00,0xc9,61,0);a.branch(0xf0,'hatchet');a.emit(0xc9,66,0);a.branch(0xd0,'done');
    a.label('hatchet');a.emit(0xa9,hi,bank,0x85,0x08,0xa9,lo,hi,0x85,0x07);
    a.label('done');a.emit(0x6b);
  });
  install(0x2f4ad,menuPrefix,menu,0x22,'hatchet menu frame selection');
  return {assembly,assemblyBytes:frames.length,weaponIds:[61,66],hooks,extraVramBytes:0,extraWramBytes:0};
}
