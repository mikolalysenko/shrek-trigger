// Replaced packets can be adjacent even when their ownership proofs differ.
// Join only touching, proven spans in the same bank. A one-byte gap or bank
// boundary remains a hard limit; neither padding nor live data is reclaimed.
export function coalesceReclaimedPools(spans){
  const ordered=spans.map(p=>({...p})).sort((a,b)=>a.next-b.next),out=[];
  for(const p of ordered){
    if(!Number.isInteger(p.next)||!Number.isInteger(p.end)||p.next<0||p.end<p.next)throw Error('Invalid reclaimed span');
    if(p.next===p.end)continue;
    if((p.next>>16)!==((p.end-1)>>16))throw Error('Reclaimed span crosses a bank');
    const previous=out.at(-1);
    if(previous&&p.next<previous.end)throw Error('Reclaimed spans overlap');
    if(previous&&previous.end===p.next&&(previous.next>>16)===(p.next>>16))previous.end=p.end;
    else out.push(p);
  }
  return out;
}

