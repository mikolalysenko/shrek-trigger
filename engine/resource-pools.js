export function replacedPacketPools(rom){
  const references=new Map(packets.map(([pointer])=>[u24(rom,pointer),[]]));
  // Conservatively retain a packet if its complete pointer occurs anywhere
  // else in the source ROM, including accidental matches in compressed data.
  // This single pass also catches aliases outside the main resource tables.
  for(let p=0;p+2<rom.length;p++){
    const refs=references.get(u24(rom,p));if(refs)refs.push(p);
  }
  const out=[];
  for(const [pointer,decodedBytes,label]of packets){
    const source=u24(rom,pointer),refs=references.get(source);
    if(refs.length!==1||refs[0]!==pointer)continue;
    const offset=fileOffset(source),packet=decompress(rom,offset);
    if(packet.bytes.length!==decodedBytes)throw Error('Replaced resource layout changed: '+label);
    out.push({pointer,offset,length:packet.length,decodedBytes,label});
  }
  return out;
}

// Carnival and swamp music completely replace these two sequences. Their
// source packets are length-prefixed; reclaim neither adjacent instruments
// nor padding, and retain any packet with another complete pointer owner.
export function replacedMusicPools(rom){
  const out=[];
  for(const[id,offset,length]of[[81,0xbe88f,1426],[82,0xbee21,835]]){
    const pointer=0x70d18+id*3,source=u24(rom,pointer);
    if(fileOffset(source)!==offset||u16(rom,offset)+2!==length)throw Error('Retired music packet layout changed');
    const refs=[];
    for(let p=0;p+2<rom.length;p++)if(u24(rom,p)===source)refs.push(p);
    if(refs.length!==1||refs[0]!==pointer)continue;
    out.push({id,pointer,offset,length});
  }
  return out;
}
