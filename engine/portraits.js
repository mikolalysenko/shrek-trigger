// Registered portraits own one existing 48x48 menu slot and the same palette
// as their character. Expose source provenance for the ROM build audit.
export function portraitArtInfo(id){
  const actor=cast[id];if(!actor)throw Error('Unknown portrait '+id);
  const key=actor.key+'-portrait',info=rasterArtInfo(key);
  if(!info)return null;
  if(info.width!==48||info.height!==48)throw Error(`Invalid generated portrait dimensions: ${key}`);
  if(info.palette?.length!==12||!actor.palette.every((color,i)=>info.palette[i]===color))throw Error(`Generated portrait palette differs from character: ${key}`);
  if(!info.sequences?.idle?.[1]?.length)throw Error(`Missing generated portrait idle pose: ${key}`);
  return {key,...info};
}

