// Places a phrase with its first downbeat at `start` ticks, transposed.
export function place(phrase,start,transpose,{from=-1,to=Infinity,trim={}}={}){
  return phrase.notes.filter(([bar])=>bar>=from&&bar<to).map(([bar,tick,ticks,pitch],i)=>{
    const key=bar+':'+tick;return[start+bar*192+tick,trim[key]??ticks,pitch+transpose];
  });
}
